export function getShape(type, rotation) {
  const piece = SHAPES[type];
  if (!piece) throw new Error(`Unknown piece type: ${type}`);
  const rot = ((rotation % 4) + 4) % 4;
  return piece.rotations[rot];
}

export function getColor(type) {
  const piece = SHAPES[type];
  if (!piece) throw new Error(`Unknown piece type: ${type}`);
  return piece.color;
}

export function createPiece(type, x, y) {
  return { type, x, y, rotation: 0 };
}

// Simplified SRS wall kick tables (JLSTZ share one; I has its own; O has none)
const JLSTZ_KICKS = {
  '0>1': [[0,0], [-1,0], [-1,1], [0,-2], [-1,-2]],
  '1>0': [[0,0], [1,0], [1,-1], [0,2], [1,2]],
  '1>2': [[0,0], [1,0], [1,1], [0,-2], [1,-2]],
  '2>1': [[0,0], [-1,0], [-1,-1], [0,2], [-1,2]],
  '2>3': [[0,0], [1,0], [1,-1], [0,2], [1,2]],
  '3>2': [[0,0], [-1,0], [-1,1], [0,-2], [-1,-2]],
  '3>0': [[0,0], [-1,0], [-1,-1], [0,2], [-1,2]],
  '0>3': [[0,0], [1,0], [1,1], [0,-2], [1,-2]],
};

const I_KICKS = {
  '0>1': [[0,0], [-2,0], [1,0], [-2,-1], [1,2]],
  '1>0': [[0,0], [2,0], [-1,0], [2,1], [-1,-2]],
  '1>2': [[0,0], [-1,0], [2,0], [-1,2], [2,-1]],
  '2>1': [[0,0], [1,0], [-2,0], [1,-2], [-2,1]],
  '2>3': [[0,0], [2,0], [-1,0], [2,1], [-1,-2]],
  '3>2': [[0,0], [-2,0], [1,0], [-2,-1], [1,2]],
  '3>0': [[0,0], [1,0], [-2,0], [1,-2], [-2,1]],
  '0>3': [[0,0], [-1,0], [2,0], [-1,2], [2,-1]],
};

export function getWallKicks(type, fromRotation, toRotation) {
  if (type === 'O') return [[0, 0]];

  const key = `${((fromRotation % 4) + 4) % 4}>${((toRotation % 4) + 4) % 4}`;
  const table = type === 'I' ? I_KICKS : JLSTZ_KICKS;
  return table[key] || [[0, 0]];
}
